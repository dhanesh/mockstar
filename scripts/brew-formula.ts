// Renders the Homebrew formula for dhanesh/homebrew-tap (Formula/mockstar.rb).
//
// Usage: bun run scripts/brew-formula.ts <version> <sha256-dir>
//   <version>     release version without the leading `v` (e.g. 0.4.0)
//   <sha256-dir>  directory searched recursively for the release's
//                 mockstar-bun-<os>-<arch>.sha256 files (`<hash>  <path>` format,
//                 as written by release.yml's build-binaries job)
//
// Prints the formula to stdout. release.yml's update-homebrew-tap job pipes it
// into the tap; docs/releasing.md covers the manual path.

import { readFileSync, readdirSync } from "node:fs";
import { basename, join } from "node:path";

const TARGETS = ["darwin-arm64", "darwin-x64", "linux-arm64", "linux-x64"] as const;
type Target = (typeof TARGETS)[number];

function findSha256Files(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return findSha256Files(path);
    return entry.name.endsWith(".sha256") ? [path] : [];
  });
}

function readHashes(dir: string): Record<Target, string> {
  const hashes: Partial<Record<Target, string>> = {};
  for (const file of findSha256Files(dir)) {
    const target = basename(file, ".sha256").replace(/^mockstar-bun-/, "") as Target;
    if (!TARGETS.includes(target)) continue;
    const hash = readFileSync(file, "utf8").trim().split(/\s+/)[0] ?? "";
    if (!/^[a-f0-9]{64}$/.test(hash)) throw new Error(`${file}: not a sha256 digest`);
    hashes[target] = hash;
  }
  const missing = TARGETS.filter((t) => !hashes[t]);
  if (missing.length > 0) throw new Error(`missing sha256 for: ${missing.join(", ")}`);
  return hashes as Record<Target, string>;
}

function render(version: string, hashes: Record<Target, string>): string {
  const base = `https://github.com/dhanesh/mockstar/releases/download/v${version}`;
  const resource = (target: Target, indent: string) =>
    [`${indent}url "${base}/mockstar-bun-${target}"`, `${indent}sha256 "${hashes[target]}"`].join("\n");

  return `# Generated by scripts/brew-formula.ts in dhanesh/mockstar — do not edit by hand.
class Mockstar < Formula
  desc "Bun-based mock server with static + dynamic mocking and multi-tenancy"
  homepage "https://dhanesh.github.io/mockstar/"
  license "MIT"

  on_macos do
    on_arm do
${resource("darwin-arm64", "      ")}
    end
    on_intel do
${resource("darwin-x64", "      ")}
    end
  end

  on_linux do
    on_arm do
${resource("linux-arm64", "      ")}
    end
    on_intel do
${resource("linux-x64", "      ")}
    end
  end

  def install
    bin.install Dir["mockstar-bun-*"].first => "mockstar"
  end

  service do
    # Scaffold starter mocks on first start (init never overwrites existing files),
    # then serve them. Done here rather than in post_install, which Homebrew deprecates.
    run ["/bin/sh", "-c", "\\"$0\\" init \\"$1\\" >/dev/null && exec \\"$0\\" serve \\"$1/mocks\\"",
         opt_bin/"mockstar", var/"mockstar"]
    working_dir var
    keep_alive true
    log_path var/"log/mockstar.log"
    error_log_path var/"log/mockstar.log"
  end

  def caveats
    <<~EOS
      Serve a mocks directory in the foreground:
        mockstar serve ./mocks

      Or run it in the background on http://127.0.0.1:3000 with:
        brew services start mockstar
      which serves #{var}/mockstar/mocks (one subdirectory per tenant).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/mockstar --version")
    system bin/"mockstar", "init", testpath
    assert_path_exists testpath/"mocks/default/example.json"
  end
end
`;
}

const [version, dir] = process.argv.slice(2);
if (!version || !dir || version.startsWith("v")) {
  console.error("usage: bun run scripts/brew-formula.ts <version-without-v> <sha256-dir>");
  process.exit(2);
}
process.stdout.write(render(version, readHashes(dir)));
